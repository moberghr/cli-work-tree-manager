export function mountDemoReviews(app: Hono, broadcast: (event: string, data: unknown) => void): void {
  const now = new Date();
  const reviews = new Map<string, PrReviewWire>([
    ['api#231', demoReview(now)],
    ['api#236', waitingReview(new Date(now.getTime() - 3_600_000))],
  ]);
  const modes: Record<string, ReviewMode> = { api: 'all', web: 'asked', docs: 'off' };
  const settings = (): ReviewSettingsWire => ({
    projects: Object.entries(modes).map(([name, mode]) => ({ name, kind: 'repo' as const, mode, from: 'repo' as const })),
    maxPerDay: null,
    maxLines: 3000,
  });
  const key = (repo: string, n: string) => `${repo}#${n}`;

  app.get('/api/reviews', (c) =>
    c.json({
      reviews: [...reviews.values()].map(summaryOf).sort((a, b) => b.at.localeCompare(a.at)),
      today: 1,
      maxPerDay: null,
    } satisfies ReviewsWire),
  );
  app.get('/api/reviews/settings', (c) => c.json(settings()));
  app.put('/api/reviews/settings', async (c) => {
    const body = (await c.req.json().catch(() => null)) as { project?: unknown; mode?: unknown } | null;
    if (!body || typeof body.project !== 'string' || !isReviewMode(body.mode))
      return c.json({ error: 'expected {project, mode: all|asked|off}' }, 400);
    modes[body.project] = body.mode;
    broadcast('reviews-changed', { settings: true });
    return c.json(settings());
  });
  app.get('/api/reviews/:repo/:number', (c) => {
    const r = reviews.get(key(c.req.param('repo'), c.req.param('number')));
    return r ? c.json(r) : c.json({ error: 'no review of that PR' }, 404);
  });
  app.get('/api/reviews/:repo/:number/diff', (c) => {
    const r = reviews.get(key(c.req.param('repo'), c.req.param('number')));
    return r && r.status === 'ready' ? c.json({ files: FILES }) : c.json({ error: 'no prepared review of that PR' }, 404);
  });
  app.post('/api/reviews/:repo/:number', (c) => {
    const k = key(c.req.param('repo'), c.req.param('number'));
    const was = reviews.get(k);
    if (!was) return c.json({ error: "isn't an open pull request" }, 409);
    // The demo's prepared review stands in for any PR prepared now.
    const r = { ...demoReview(new Date()), number: was.number, title: was.title, url: was.url, author: was.author };
    reviews.set(k, r);
    broadcast('reviews-changed', { repo: r.repo, number: r.number });
    return c.json(r);
  });
  app.post('/api/reviews/:repo/:number/drafts', async (c) => {
    const k = key(c.req.param('repo'), c.req.param('number'));
    const r = reviews.get(k);
    if (!r) return c.json({ error: 'no review of that PR' }, 404);
    const added = addDraft(r, await c.req.json().catch(() => null));
    if ('error' in added) return c.json({ error: added.error }, 400);
    reviews.set(k, added.review);
    broadcast('reviews-changed', { repo: r.repo, number: r.number });
    return c.json(added.review);
  });
  app.post('/api/reviews/:repo/:number/submit', async (c) => {
    const k = key(c.req.param('repo'), c.req.param('number'));
    const r = reviews.get(k);
    if (!r) return c.json({ error: 'no review of that PR' }, 404);
    const input: unknown = await c.req.json().catch(() => null);
    const refusal = submitRefusal(r, input);
    if (refusal) return c.json({ error: refusal }, 400);
    const next = afterSubmit(r, input as ReviewSubmitInput, `${r.url}#pullrequestreview-1`, new Date());
    reviews.set(k, next);
    broadcast('reviews-changed', { repo: r.repo, number: r.number });
    return c.json(next);
  });
  app.delete('/api/reviews/:repo/:number/drafts/:id', (c) => {
    const k = key(c.req.param('repo'), c.req.param('number'));
    const r = reviews.get(k);
    if (!r) return c.json({ error: 'no review of that PR' }, 404);
    const next = { ...r, drafts: r.drafts.filter((d) => d.id !== c.req.param('id') || d.state === 'posted') };
    reviews.set(k, next);
    broadcast('reviews-changed', { repo: r.repo, number: r.number });
    return c.json(next);
  });
}
