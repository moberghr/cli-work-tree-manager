/** The demo's sessions, for Fix it myself: the live one on a branch, a new one started with a prompt, a note to one. */
export interface DemoReviewSessions {
  liveOn: (alias: string, branch: string) => { id: string; label: string } | null;
  /** A new session on the branch (`name`: what it's called). */
  create: (alias: string, branch: string, name: string) => { id: string; label: string };
  note: (id: string, body: string) => void;
}

/** Sessions nobody keeps (the parity test's): every one is new, notes go nowhere. */
const noSessions: DemoReviewSessions = {
  liveOn: () => null,
  create: (alias, branch) => ({ id: `${alias}-${branch}`, label: `${alias} · ${branch}` }),
  note: () => undefined,
};

export function mountDemoReviews(
  app: Hono,
  broadcast: (event: string, data: unknown) => void,
  sessions: DemoReviewSessions = noSessions,
): void {
  const now = new Date();
  const reviews = new Map<string, PrReviewWire>([
    ['api#231', demoReview(now)],
    ['api#236', waitingReview(new Date(now.getTime() - 3_600_000))],
  ]);
  const modes: Record<string, ReviewMode> = { api: 'all', web: 'asked', docs: 'off' };
  const settings = (): ReviewSettingsWire => ({
    projects: Object.entries(modes).map(([name, mode]) => ({ name, kind: 'repo' as const, mode, from: 'repo' as const })),
    maxPerDay: null,
    maxLines: 3000,
  });
  const key = (repo: string, n: string) => `${repo}#${n}`;
  // The submit flow's store and claim owner, as work web's (one process that never stops: no claim is left over).
  const store = {
    read: (rp: string, num: number) => reviews.get(key(rp, String(num))) ?? null,
    update: (rp: string, num: number, change: (r: PrReviewWire) => PrReviewWire) => {
      const was = reviews.get(key(rp, String(num)));
      if (!was) return null;
      const next = change(was);
      reviews.set(key(rp, String(num)), next);
      return next;
    },
    pid: 0,
    bootedAt: () => 0,
    alive: () => true,
  };

  app.get('/api/reviews', (c) =>
    c.json({
      reviews: [...reviews.values()].map(summaryOf).sort((a, b) => b.at.localeCompare(a.at)),
      today: 1,
      maxPerDay: null,
    } satisfies ReviewsWire),
  );
  app.get('/api/reviews/settings', (c) => c.json(settings()));
  app.put('/api/reviews/settings', async (c) => {
    const body = (await c.req.json().catch(() => null)) as { project?: unknown; mode?: unknown } | null;
    if (!body || typeof body.project !== 'string' || !isReviewMode(body.mode))
      return c.json({ error: 'expected {project, mode: all|asked|off}' }, 400);
    modes[body.project] = body.mode;
    broadcast('reviews-changed', { settings: true });
    return c.json(settings());
  });
  app.get('/api/reviews/:repo/:number', (c) => {
    const r = reviews.get(key(c.req.param('repo'), c.req.param('number')));
    return r ? c.json(shownReview(store, r)) : c.json({ error: 'no review of that PR' }, 404);
  });
  app.get('/api/reviews/:repo/:number/diff', (c) => {
    const r = reviews.get(key(c.req.param('repo'), c.req.param('number')));
    return r && r.status === 'ready' ? c.json({ files: FILES }) : c.json({ error: 'no prepared review of that PR' }, 404);
  });
  app.post('/api/reviews/:repo/:number', (c) => {
    const k = key(c.req.param('repo'), c.req.param('number'));
    const was = reviews.get(k);
    if (!was) return c.json({ error: "isn't an open pull request" }, 409);
    // The demo's prepared review stands in for any PR prepared now.
    const r = { ...demoReview(new Date()), number: was.number, title: was.title, url: was.url, author: was.author };
    reviews.set(k, r);
    broadcast('reviews-changed', { repo: r.repo, number: r.number });
    return c.json(r);
  });
  app.post('/api/reviews/:repo/:number/drafts', async (c) => {
    const k = key(c.req.param('repo'), c.req.param('number'));
    const r = reviews.get(k);
    if (!r) return c.json({ error: 'no review of that PR' }, 404);
    const added = addDraft(r, await c.req.json().catch(() => null));
    if ('error' in added) return c.json({ error: added.error }, 400);
    reviews.set(k, added.review);
    broadcast('reviews-changed', { repo: r.repo, number: r.number });
    return c.json(added.review);
  });
  app.post('/api/reviews/:repo/:number/submit', async (c) => {
    const repo = c.req.param('repo');
    const n = /^\d+$/.test(c.req.param('number')) ? Number(c.req.param('number')) : null;
    if (n === null) return c.json({ error: 'no review of that PR' }, 404);
    const input: unknown = await c.req.json().catch(() => null);
    const out = await submitPrReview(
      {
        ...store,
        repoPath: (alias) => (alias === 'api' ? '/demo/api' : null),
        submit: async (_at, num, review) => demoHostSubmit(reviews.get(key(repo, String(num)))?.url ?? '', review),
      },
      repo,
      n,
      input,
    );
    if (out.ok || out.review) broadcast('reviews-changed', { repo, number: n });
    if (out.ok) return c.json(out.review);
    return c.json({ error: out.error, ...(out.review ? { review: out.review } : {}) }, out.status);
  });
  // Fix it myself: the real flow (`fixItMyself`) over the demo's reviews and sessions; a fork's PR is refused as there.
  app.post('/api/reviews/:repo/:number/fix-myself', async (c) => {
    const repo = c.req.param('repo');
    const n = /^\d+$/.test(c.req.param('number')) ? Number(c.req.param('number')) : null;
    if (n === null || !reviews.get(key(repo, String(n)))) return c.json({ error: 'no review of that PR' }, 404);
    const input: unknown = await c.req.json().catch(() => null);
    const out = await fixItMyself(
      {
        read: store.read,
        update: store.update,
        lookUp: async (r) =>
          r.fork
            ? { ok: false, error: "it comes from a fork: its branch isn't on origin" }
            : {
                ok: true,
                pr: { alias: r.repo, number: r.number, title: r.title, url: r.url, branch: r.branch, base: r.base, author: r.author },
              },
        liveSessionOn: (alias, branch) => sessions.liveOn(alias, branch),
        create: async (alias, branch, name) => {
          const s = sessions.create(alias, branch, name);
          return { ok: true, sessionId: s.id, label: s.label };
        },
        // The demo's agent "starts" on its instruction: a note it answers, as every demo note.
        start: async (id, prompt) => sessions.note(id, prompt),
        note: async (id, body) => sessions.note(id, body),
      },
      repo,
      n,
      input,
    );
    if (!out.ok) return c.json({ error: out.error }, out.status);
    broadcast('reviews-changed', { repo, number: n });
    broadcast('sessions-changed', { ts: Date.now() });
    const { ok: _ok, ...wire } = out;
    return c.json(wire satisfies ReviewFixResultWire);
  });
  app.post('/api/reviews/:repo/:number/in-doubt', async (c) => {
    const k = key(c.req.param('repo'), c.req.param('number'));
    const r = reviews.get(k);
    if (!r) return c.json({ error: 'no review of that PR' }, 404);
    const body = (await c.req.json().catch(() => null)) as { went?: unknown } | null;
    if (!body || typeof body.went !== 'boolean') return c.json({ error: 'expected {went: true|false}' }, 400);
    const out = settlePrReview(store, r.repo, r.number, body.went);
    if (!out.ok) return c.json({ error: out.error }, out.status);
    broadcast('reviews-changed', { repo: r.repo, number: r.number });
    return c.json(out.review);
  });
  app.delete('/api/reviews/:repo/:number/dropped', (c) => {
    const k = key(c.req.param('repo'), c.req.param('number'));
    const r = reviews.get(k);
    if (!r) return c.json({ error: 'no review of that PR' }, 404);
    const next = clearDropped(r);
    reviews.set(k, next);
    broadcast('reviews-changed', { repo: r.repo, number: r.number });
    return c.json(next);
  });
  app.delete('/api/reviews/:repo/:number/drafts/:id', (c) => {
    const k = key(c.req.param('repo'), c.req.param('number'));
    const r = reviews.get(k);
    if (!r) return c.json({ error: 'no review of that PR' }, 404);
    const out = removeDraft(r, c.req.param('id'));
    if ('error' in out) return c.json({ error: out.error }, out.status);
    reviews.set(k, out.review);
    broadcast('reviews-changed', { repo: r.repo, number: r.number });
    return c.json(out.review);
  });
}
