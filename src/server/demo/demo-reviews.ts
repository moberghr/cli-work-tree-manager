const hunk = (path: string, lines: string[], status: 'added' | 'modified' = 'modified') => {
  const added = lines.filter((l) => l.startsWith('+')).length;
  const deleted = lines.filter((l) => l.startsWith('-')).length;
  const context = lines.length - added - deleted;
  return [
    `diff --git a/${path} b/${path}`,
    ...(status === 'added'
      ? ['new file mode 100644', 'index 0000000..1111111', '--- /dev/null']
      : ['index 1111111..2222222 100644', `--- a/${path}`]),
    `+++ b/${path}`,
    `@@ -${status === 'added' ? 0 : 1},${status === 'added' ? 0 : context + deleted} +1,${context + added} @@`,
    ...lines,
  ].join('\n');
};

