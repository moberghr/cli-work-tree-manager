export function demoReview(now = new Date()): PrReviewWire {
  return {
    ...buildReview(
      {
        repo: 'api',
        number: 231,
        title: 'Refunds: partial refunds on paid orders',
        url: 'https://github.com/example/api/pull/231',
        author: 'marta',
        branch: 'feat/refunds',
        base: 'main',
        headSha: 'a1b2c3d',
      },
      FILES,
      { whitespaceOnly: new Set(), generated: new Set() },
      DEMO_ANSWER,
      { now },
    ),
    mergeBase: 'base',
    preparedAt: now.toISOString(),
  };
}

